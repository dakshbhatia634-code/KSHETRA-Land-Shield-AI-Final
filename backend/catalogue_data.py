def get_catalogue_locations(
    state: str = None,
    dominant_type: str = None,
    query: str = None,
    limit: int = 50
) -> List[Dict[str, Any]]:
    """Filters and returns catalogue locations with source metadata."""
    results = INDIA_LAND_CATALOGUE

    if state:
        results = [loc for loc in results if loc["state"].lower() == state.lower()]
    if dominant_type:
        results = [loc for loc in results if loc["dominant_type"].lower() == dominant_type.lower()]
    if query:
        q = query.lower()
        results = [
            loc for loc in results
            if q in loc["name"].lower() or q in loc["state"].lower() or q in loc["district"].lower() or q in loc["terrain"].lower()
        ]

    return results[:limit]
